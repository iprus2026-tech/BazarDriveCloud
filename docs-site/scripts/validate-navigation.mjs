#!/usr/bin/env node
// BD-DOCS-SITE-06 — Mini-Yonder docs-site navigation validator.
//
// Locks the repository file inventory page into docs-site navigation so it can
// never silently become a hidden, slug-only URL that works only when someone
// already knows the address. It also guards the sidebar itself: every sidebar
// entry must resolve to a real governed document, never to a dangling id, a
// stale internal URL, or an underscore-prefixed scaffold under _templates.
//
// Concretely it asserts:
//   • every sidebar item resolves to a governed doc — across the supported
//     Docusaurus item forms (string / doc / ref / category link / autogenerated
//     / link) — so no dangling, stale, or template entry can slip in,
//   • the inventory page is present in the docs-site sidebar navigation,
//   • the docs-site index (landing page) links to the inventory page by its
//     exact target (not merely a string that contains its name), and
//   • the inventory page keeps its clean slug.
//
// STRICT: any failure exits 1 (with per-error detail) so `npm run check` and CI
// gate on it. Standard: docs-site/docs/governance/repository-file-inventory.md.

import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, sep, extname, basename, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import matter from 'gray-matter';
import yaml from 'js-yaml';

const require = createRequire(import.meta.url);

const SCRIPTS_DIR = fileURLToPath(new URL('.', import.meta.url));
const SITE_ROOT = join(SCRIPTS_DIR, '..'); // docs-site/
const DOCS_DIR = join(SITE_ROOT, 'docs');
const SIDEBARS_PATH = join(SITE_ROOT, 'sidebars.js');
const CONFIG_PATH = join(SITE_ROOT, 'docusaurus.config.js');
const INDEX_DOC = join(DOCS_DIR, 'index.md');

// The page this slice locks into navigation. Identified by its file (the stable
// anchor) — its Docusaurus id and slug are read from frontmatter, never guessed.
const INVENTORY_REL = 'governance/repository-file-inventory.md'; // under docs/
const INVENTORY_SLUG = '/governance/repository-file-inventory';

// Keep YAML dates as raw strings (no Date coercion), matching the other validators.
const MATTER_OPTS = {
  engines: { yaml: (s) => yaml.load(s, { schema: yaml.JSON_SCHEMA }) },
};

function toPosix(p) {
  return String(p).split(sep).join('/');
}

function stripTrailingSlash(s) {
  return s.length > 1 ? s.replace(/\/+$/, '') : s;
}

// Build the governed-doc universe: a map of Docusaurus doc id -> { rel, route }.
// Mirrors Docusaurus' own id/route derivation — id = <dirFromDocs>/<frontmatter
// id || filename>, route = explicit slug || `/<id>` — and skips underscore-
// prefixed scaffolds (templates/partials), exactly like validate-frontmatter.mjs
// and the inventory scanner. A sidebar entry that points at a scaffold therefore
// resolves to nothing and is reported.
function collectDocs() {
  const map = new Map();
  (function walk(dir) {
    for (const name of readdirSync(dir)) {
      if (name.startsWith('_')) continue; // scaffolds are not governed pages
      const abs = join(dir, name);
      const st = statSync(abs);
      if (st.isDirectory()) {
        walk(abs);
        continue;
      }
      if (!/\.(md|mdx)$/.test(name)) continue;
      let data = {};
      try {
        ({ data } = matter(readFileSync(abs, 'utf8'), MATTER_OPTS));
      } catch {
        continue; // malformed frontmatter is validate-frontmatter.mjs' job
      }
      const dirFromDocs = toPosix(relative(DOCS_DIR, dirname(abs)));
      const idSeg =
        typeof data.id === 'string' && data.id.trim() !== ''
          ? data.id.trim()
          : basename(name, extname(name));
      const docId = dirFromDocs ? `${dirFromDocs}/${idSeg}` : idSeg;
      const slug = typeof data.slug === 'string' ? data.slug : null;
      map.set(docId, {
        rel: toPosix(relative(DOCS_DIR, abs)),
        route: stripTrailingSlash(slug || `/${docId}`),
      });
    }
  })(DOCS_DIR);
  return map;
}

// Walk every named sidebar and collect the supported item forms separately:
//   • docIds — string / {type:'doc'|'ref'} / category {link:{type:'doc'}}
//   • autogen — {type:'autogenerated', dirName} (expanded against the doc tree)
//   • links — {type:'link', href} (validated against governed-doc routes)
// Anything else with an `items` array is still recursed into.
function walkSidebar(node, acc) {
  if (typeof node === 'string') {
    acc.docIds.push(node);
    return;
  }
  if (Array.isArray(node)) {
    for (const n of node) walkSidebar(n, acc);
    return;
  }
  if (node && typeof node === 'object') {
    if ((node.type === 'doc' || node.type === 'ref') && typeof node.id === 'string') {
      acc.docIds.push(node.id);
    } else if (node.type === 'link' && typeof node.href === 'string') {
      acc.links.push(node.href);
    } else if (node.type === 'autogenerated' && typeof node.dirName === 'string') {
      acc.autogen.push(node.dirName);
    }
    // A category may carry a `link` of its own (type 'doc' resolves to a doc;
    // 'generated-index' is a synthetic page with a slug, not a governed doc).
    if (node.link && node.link.type === 'doc' && typeof node.link.id === 'string') {
      acc.docIds.push(node.link.id);
    }
    if (Array.isArray(node.items)) walkSidebar(node.items, acc);
  }
}

// Expand an autogenerated dirName to the governed doc ids it would pull in.
function expandAutogen(dirName, docMap) {
  const norm = dirName.replace(/^\.?\/?/, '').replace(/\/$/, '');
  const prefix = norm === '' || norm === '.' ? '' : `${norm}/`;
  const ids = [];
  for (const [docId, info] of docMap) {
    if (prefix === '' || info.rel.startsWith(prefix)) ids.push(docId);
  }
  return ids;
}

function looksLikeTemplate(s) {
  return s.split('/').some((seg) => seg.startsWith('_'));
}

function isExternalHref(href) {
  return /^(https?:)?\/\//.test(href) || /^(mailto|tel):/.test(href) || href.startsWith('#');
}

function main() {
  const errors = [];

  // --- Read baseUrl (to normalize internal hrefs/slugs) -------------------
  let baseUrl = '/';
  try {
    const cfg = require(CONFIG_PATH);
    if (cfg && typeof cfg.baseUrl === 'string') baseUrl = cfg.baseUrl;
  } catch {
    /* fall back to '/'; an unreadable config is docusaurus build's concern */
  }
  // Strip an optional leading baseUrl from an internal path, leaving a root-
  // relative route (e.g. /bazardrive-docs/governance/x -> /governance/x).
  const stripBase = (p) => {
    let h = p.split('#')[0].split('?')[0];
    const b = stripTrailingSlash(baseUrl);
    if (b !== '' && b !== '/' && (h === b || h.startsWith(`${b}/`))) {
      h = h.slice(b.length) || '/';
    }
    return stripTrailingSlash(h);
  };

  // --- Inputs -------------------------------------------------------------
  if (!existsSync(SIDEBARS_PATH)) {
    console.error(`validate-navigation: sidebars.js not found at ${toPosix(relative(SITE_ROOT, SIDEBARS_PATH))}`);
    process.exit(1);
  }
  let sidebars;
  try {
    sidebars = require(SIDEBARS_PATH);
  } catch (err) {
    console.error(`validate-navigation: cannot load sidebars.js — ${err.message}`);
    process.exit(1);
  }

  const docMap = collectDocs();
  const validRoutes = new Set([...docMap.values()].map((info) => info.route));

  // sidebars.js exports an object keyed by sidebar name (e.g. { docsSidebar:
  // [...] }); walk every named sidebar's item tree.
  const acc = { docIds: [], links: [], autogen: [] };
  if (sidebars && typeof sidebars === 'object') {
    for (const sidebar of Object.values(sidebars)) walkSidebar(sidebar, acc);
  }
  // Expand autogenerated entries into the governed doc ids they cover.
  for (const dirName of acc.autogen) acc.docIds.push(...expandAutogen(dirName, docMap));
  const sidebarDocSet = new Set(acc.docIds);

  // --- 1a. Every sidebar doc entry must resolve to a governed, non-template doc.
  for (const id of acc.docIds) {
    if (!docMap.has(id)) {
      errors.push(
        looksLikeTemplate(id)
          ? `sidebar entry "${id}" points at an underscore/template scaffold — templates must not appear in navigation`
          : `sidebar entry "${id}" does not resolve to any governed doc (dangling navigation id)`,
      );
    }
  }

  // --- 1b. Every internal sidebar link must resolve to a governed-doc route.
  for (const href of acc.links) {
    if (isExternalHref(href)) continue; // external links are out of scope
    if (!href.startsWith('/')) {
      errors.push(`sidebar link href "${href}" must be an absolute internal route (starting with "/") or an external URL`);
      continue;
    }
    const route = stripBase(href);
    if (!validRoutes.has(route)) {
      errors.push(
        looksLikeTemplate(route)
          ? `sidebar link href "${href}" points at an underscore/template path — templates must not appear in navigation`
          : `sidebar link href "${href}" does not resolve to any governed-doc route (stale/dangling navigation link)`,
      );
    }
  }

  // --- 2. Locate the inventory page by its file (stable anchor).
  let inventoryId = null;
  let inventorySlug = null;
  for (const [docId, info] of docMap) {
    if (info.rel === INVENTORY_REL) {
      inventoryId = docId;
      inventorySlug = docMap.get(docId).route;
      break;
    }
  }

  if (inventoryId === null) {
    errors.push(`inventory page not found / not governed at docs/${INVENTORY_REL}`);
  } else {
    // --- 3. Clean slug intact.
    if (inventorySlug !== INVENTORY_SLUG) {
      errors.push(
        `inventory page route is "${inventorySlug}" — must be the clean slug "${INVENTORY_SLUG}"`,
      );
    }
    // --- 4. Present in the docs-site sidebar navigation.
    if (!sidebarDocSet.has(inventoryId)) {
      errors.push(
        `inventory page ("${inventoryId}") is missing from the docs-site sidebar (sidebars.js) — it would be a hidden, slug-only URL`,
      );
    }
  }

  // --- 5. Linked from the docs-site index (landing page) by EXACT target.
  // Matching the substring "repository-file-inventory" is not enough: a typo'd
  // target (…-old.md) or an external URL containing that text would pass while
  // the entry point is actually broken, and onBrokenMarkdownLinks is warn-only.
  if (!existsSync(INDEX_DOC)) {
    errors.push('docs-site index (docs/index.md) not found');
  } else {
    const indexText = readFileSync(INDEX_DOC, 'utf8');
    const indexDir = '.'; // docs/index.md lives at the docs root
    let linked = false;
    for (const m of indexText.matchAll(/\]\(\s*(<[^>]+>|[^)\s]+)/g)) {
      let target = m[1].replace(/^<|>$/g, '').trim();
      if (!target) continue;
      const noAnchor = target.split('#')[0].split('?')[0];
      if (!noAnchor) continue;
      // slug form (optionally baseUrl-prefixed)
      if (stripBase(noAnchor) === INVENTORY_SLUG) {
        linked = true;
        break;
      }
      // relative markdown form — resolve against the index file's directory
      if (/\.mdx?$/.test(noAnchor) && !noAnchor.startsWith('/') && !isExternalHref(noAnchor)) {
        const resolved = posix.normalize(posix.join(indexDir, noAnchor)).replace(/^\.\//, '');
        if (resolved === INVENTORY_REL) {
          linked = true;
          break;
        }
      }
    }
    if (!linked) {
      errors.push(
        `docs-site index (docs/index.md) does not link to the inventory page by its exact target (expected the .md link "${INVENTORY_REL}" or the slug "${INVENTORY_SLUG}")`,
      );
    }
  }

  // --- Report -------------------------------------------------------------
  if (errors.length > 0) {
    console.error('Docs-site navigation validation failed:\n');
    for (const e of errors) console.error(`  ✗ ${e}`);
    console.error(`\n${errors.length} error(s).`);
    process.exit(1);
  }

  console.log(
    `✓ Navigation OK — ${acc.docIds.length} sidebar doc entr(y/ies) + ${acc.links.length} link(s) resolve; ` +
      `inventory page "${inventoryId}" is in the sidebar, linked from the index by exact target, and keeps its clean slug.`,
  );
  process.exit(0);
}

main();
