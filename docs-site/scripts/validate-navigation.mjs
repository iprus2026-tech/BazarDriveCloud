#!/usr/bin/env node
// BD-DOCS-SITE-06 — Mini-Yonder docs-site navigation validator.
//
// Locks the repository file inventory page into docs-site navigation so it can
// never silently become a hidden, slug-only URL that works only when someone
// already knows the address. It also guards the sidebar itself: every sidebar
// entry must resolve to a real governed document, never to a dangling id, a
// stale internal URL, an underscore-prefixed scaffold under _templates, a
// generated (passport-less) page, or a draft page dropped from the build.
//
// Concretely it asserts:
//   • every sidebar item resolves to a governed, production doc — across the
//     supported Docusaurus item forms (string / doc / ref / category / category
//     shorthand / autogenerated / link); generated-index category pages
//     (explicit OR declared in an autogenerated dir's _category_ metadata) are
//     rejected as non-governed,
//   • the inventory page is present in the sidebar (as a doc entry OR a link to
//     its route) and is not draft/unlisted (which the build removes from nav),
//   • the docs-site index (landing page) links to the inventory page by its
//     exact target — inline OR an actually-used reference link — in the rendered
//     Markdown body (not frontmatter/code/comments),
//   • the inventory page keeps its exact clean slug.
//
// Doc ids / routes mirror Docusaurus' loader: directory/file number prefixes
// (01-foo) are stripped best-effort (date/version-looking segments kept; honors
// a per-doc `parse_number_prefixes: false` opt-out), a frontmatter `id`
// overrides the last segment, a relative `slug` resolves against the doc's
// directory, and a folder index (index/README/<folder>.md) maps to the
// directory route.
//
// STRICT: any failure exits 1 (with per-error detail) so `npm run check` and CI
// gate on it. Standard: docs-site/docs/governance/repository-file-inventory.md.

import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, sep, extname, basename, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import matter from 'gray-matter';
import * as yaml from 'js-yaml';

const require = createRequire(import.meta.url);

const SCRIPTS_DIR = fileURLToPath(new URL('.', import.meta.url));
const SITE_ROOT = join(SCRIPTS_DIR, '..'); // docs-site/
const DOCS_DIR = join(SITE_ROOT, 'docs');
const SIDEBARS_PATH = join(SITE_ROOT, 'sidebars.js');
const CONFIG_PATH = join(SITE_ROOT, 'docusaurus.config.js');
const INDEX_DOC = join(DOCS_DIR, 'index.md');

// The page this slice locks into navigation. Identified by its file (the stable
// anchor) — its Docusaurus id and slug are read from frontmatter, never guessed.
const INVENTORY_REL = 'governance/repository-file-inventory.md'; // under docs/
const INVENTORY_SLUG = '/governance/repository-file-inventory';

// Keep YAML dates as raw strings (no Date coercion), matching the other validators.
const MATTER_OPTS = {
  engines: { yaml: (s) => yaml.load(s, { schema: yaml.JSON_SCHEMA }) },
};

function toPosix(p) {
  return String(p).split(sep).join('/');
}

function stripTrailingSlash(s) {
  return s.length > 1 ? s.replace(/\/+$/, '') : s;
}

// Mirror Docusaurus' default number-prefix parser (best-effort): strip a single
// leading number + separator (01-foo, 1.foo, "1 - foo") from a path segment,
// but deliberately leave date/version-looking segments intact — i.e. when the
// remainder itself starts with another number+separator (2026-06-release,
// 8.0.0-foo), nothing is stripped.
function stripNumberPrefix(seg) {
  const m = seg.match(/^\d+\s*[-_.]\s*(.+)$/);
  if (!m) return seg;
  const suffix = m[1];
  if (/^\d+\s*[-_.]/.test(suffix)) return seg; // date/version-looking → leave it
  return suffix;
}

// Build the governed-doc universe: a map of Docusaurus doc id ->
// { rel, route, slug, draft, unlisted }. Underscore-prefixed scaffolds
// (templates/partials) are skipped, exactly like validate-frontmatter.mjs and
// the inventory scanner.
function collectDocs() {
  const map = new Map();
  (function walk(dir) {
    for (const name of readdirSync(dir)) {
      if (name.startsWith('_')) continue; // scaffolds are not governed pages
      const abs = join(dir, name);
      const st = statSync(abs);
      if (st.isDirectory()) {
        walk(abs);
        continue;
      }
      if (!/\.(md|mdx)$/.test(name)) continue;
      let data = {};
      try {
        ({ data } = matter(readFileSync(abs, 'utf8'), MATTER_OPTS));
      } catch {
        continue; // malformed frontmatter is validate-frontmatter.mjs' job
      }
      // Per-doc opt-out keeps the raw (number-prefixed) segments in the id/route.
      const xform = data.parse_number_prefixes === false ? (s) => s : stripNumberPrefix;
      const dirFromDocs = toPosix(relative(DOCS_DIR, dirname(abs)));
      const dirSegs = dirFromDocs === '' ? [] : dirFromDocs.split('/').map(xform);
      const dirForRoute = dirSegs.join('/');
      const baseName = basename(name, extname(name));
      const parentName = dirSegs.length ? dirSegs[dirSegs.length - 1] : '';
      const hasId = typeof data.id === 'string' && data.id.trim() !== '';
      const idVal = hasId ? data.id.trim() : null;
      // Folder index conventions: index.md / README.md / <folder>.md serve at
      // the directory route, not at `/<dir>/<file>`.
      const isFolderIndex =
        /^(index|readme)$/i.test(baseName) || (parentName !== '' && xform(baseName) === parentName);

      const aliasIds = new Set();
      let primaryId;
      if (isFolderIndex) {
        if (hasId) {
          primaryId = [...dirSegs, idVal].join('/');
        } else {
          primaryId = dirForRoute; // collapses to the folder
          if (dirForRoute) aliasIds.add(`${dirForRoute}/${xform(baseName)}`);
        }
      } else {
        primaryId = [...dirSegs, idVal ?? xform(baseName)].join('/');
      }
      aliasIds.add(primaryId);

      const slug = typeof data.slug === 'string' ? data.slug : null;
      const routeBase = isFolderIndex ? (dirForRoute ? `/${dirForRoute}` : '/') : `/${primaryId}`;
      let route;
      if (slug !== null && slug.trim() !== '') {
        route = slug.startsWith('/')
          ? stripTrailingSlash(slug) || '/'
          : stripTrailingSlash(posix.normalize(`${dirForRoute ? `/${dirForRoute}` : ''}/${slug}`)) || '/';
      } else {
        route = stripTrailingSlash(routeBase) || '/';
      }

      const info = {
        rel: toPosix(relative(DOCS_DIR, abs)),
        route,
        slug,
        draft: data.draft === true,
        unlisted: data.unlisted === true,
      };
      for (const id of aliasIds) {
        if (id !== '') map.set(id, info);
      }
    }
  })(DOCS_DIR);
  return map;
}

// Walk every named sidebar and collect the supported item forms separately.
function walkSidebar(node, acc) {
  if (typeof node === 'string') {
    acc.docIds.push(node);
    return;
  }
  if (Array.isArray(node)) {
    for (const n of node) walkSidebar(n, acc);
    return;
  }
  if (!node || typeof node !== 'object') return;

  switch (node.type) {
    case 'doc':
    case 'ref':
      if (typeof node.id === 'string') acc.docIds.push(node.id);
      return;
    case 'link':
      if (typeof node.href === 'string') acc.links.push(node.href);
      return;
    case 'autogenerated':
      if (typeof node.dirName === 'string') acc.autogen.push(node.dirName);
      return;
    case 'html':
      return; // rendered HTML, no doc reference
    case 'category':
      if (node.link && node.link.type === 'doc' && typeof node.link.id === 'string') {
        acc.docIds.push(node.link.id);
      } else if (node.link && node.link.type === 'generated-index') {
        acc.generatedIndex.push(node.label || node.link.slug || '(generated-index)');
      }
      if (Array.isArray(node.items)) walkSidebar(node.items, acc);
      return;
    case undefined:
      // Category shorthand: { 'Getting Started': ['a', 'b'], ... }.
      for (const value of Object.values(node)) walkSidebar(value, acc);
      return;
    default:
      if (Array.isArray(node.items)) walkSidebar(node.items, acc);
      return;
  }
}

// Governed doc ids pulled in by an autogenerated dirName (raw filesystem path).
function expandAutogen(dirName, docMap) {
  const norm = dirName.replace(/^\.?\/?/, '').replace(/\/$/, '');
  const prefix = norm === '' || norm === '.' ? '' : `${norm}/`;
  const ids = [];
  for (const [docId, info] of docMap) {
    if (prefix === '' || info.rel.startsWith(prefix)) ids.push(docId);
  }
  return ids;
}

// _category_.{json,yml,yaml} files under an autogenerated dir can declare a
// generated-index category page — also a passport-less generated nav page.
function autogenGeneratedIndex(absDir) {
  const found = [];
  (function walk(d) {
    for (const name of readdirSync(d)) {
      const abs = join(d, name);
      const st = statSync(abs);
      if (st.isDirectory()) {
        if (!name.startsWith('_')) walk(abs);
        continue;
      }
      if (!/^_category_\.(json|ya?ml)$/.test(name)) continue;
      let meta;
      try {
        const raw = readFileSync(abs, 'utf8');
        meta = name.endsWith('.json') ? JSON.parse(raw) : yaml.load(raw, { schema: yaml.JSON_SCHEMA });
      } catch {
        continue;
      }
      if (meta && meta.link && meta.link.type === 'generated-index') {
        found.push(meta.label || toPosix(relative(DOCS_DIR, d)) || '(generated-index)');
      }
    }
  })(absDir);
  return found;
}

function looksLikeTemplate(s) {
  return s.split('/').some((seg) => seg.startsWith('_'));
}

function isExternalHref(href) {
  // Hash-only (#anchor) hrefs are in-page/internal, NOT external.
  return /^(https?:)?\/\//.test(href) || /^(mailto|tel):/.test(href);
}

// Remove non-rendered Markdown (HTML comments, fenced and inline code) so a link
// buried in a code block or comment does not count as a real navigation entry.
function strippedMarkdown(text) {
  return text
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/```[\s\S]*?```/g, '')
    .replace(/~~~[\s\S]*?~~~/g, '')
    .replace(/`[^`\n]*`/g, '');
}

function main() {
  const errors = [];

  // --- Read baseUrl (to normalize internal hrefs/slugs) -------------------
  let baseUrl = '/';
  try {
    const cfg = require(CONFIG_PATH);
    if (cfg && typeof cfg.baseUrl === 'string') baseUrl = cfg.baseUrl;
  } catch {
    /* fall back to '/'; an unreadable config is docusaurus build's concern */
  }
  const stripBase = (p) => {
    let h = p.split('#')[0].split('?')[0];
    const b = stripTrailingSlash(baseUrl);
    if (b !== '' && b !== '/' && (h === b || h.startsWith(`${b}/`))) {
      h = h.slice(b.length) || '/';
    }
    return stripTrailingSlash(h);
  };

  // --- Inputs -------------------------------------------------------------
  if (!existsSync(SIDEBARS_PATH)) {
    console.error(`validate-navigation: sidebars.js not found at ${toPosix(relative(SITE_ROOT, SIDEBARS_PATH))}`);
    process.exit(1);
  }
  let sidebars;
  try {
    sidebars = require(SIDEBARS_PATH);
  } catch (err) {
    console.error(`validate-navigation: cannot load sidebars.js — ${err.message}`);
    process.exit(1);
  }

  // The whole governed universe, then the production view (Docusaurus drops
  // draft docs from the production build and its navigation).
  const allDocs = collectDocs();
  const docMap = new Map([...allDocs].filter(([, info]) => !info.draft));
  const validRoutes = new Set([...docMap.values()].map((info) => info.route));

  const acc = { docIds: [], links: [], autogen: [], generatedIndex: [] };
  if (sidebars && typeof sidebars === 'object') {
    for (const sidebar of Object.values(sidebars)) walkSidebar(sidebar, acc);
  }

  // --- 0. Validate autogenerated dirs, then expand the valid ones.
  for (const dirName of acc.autogen) {
    const norm = dirName.replace(/^\.?\/?/, '').replace(/\/$/, '');
    if (looksLikeTemplate(norm)) {
      errors.push(`sidebar autogenerated dirName "${dirName}" is an underscore/template path — templates must not appear in navigation`);
      continue;
    }
    const absDir = norm === '' ? DOCS_DIR : join(DOCS_DIR, norm);
    if (!(existsSync(absDir) && statSync(absDir).isDirectory())) {
      errors.push(`sidebar autogenerated dirName "${dirName}" is not an existing directory under docs/ (typo / dangling)`);
      continue;
    }
    const ids = expandAutogen(norm, docMap);
    if (ids.length === 0) {
      errors.push(`sidebar autogenerated dirName "${dirName}" pulls in no governed (non-draft) docs`);
      continue;
    }
    acc.docIds.push(...ids);
    for (const label of autogenGeneratedIndex(absDir)) acc.generatedIndex.push(label);
  }
  const sidebarDocSet = new Set(acc.docIds);

  // --- 0b. Generated-index pages have no governed doc/passport.
  for (const label of acc.generatedIndex) {
    errors.push(`sidebar category "${label}" uses a generated-index page — a generated page with no governed doc/passport is not allowed in governed navigation`);
  }

  // --- 1a. Every sidebar doc entry must resolve to a governed, non-template,
  // non-draft (production) doc.
  for (const id of acc.docIds) {
    if (!docMap.has(id)) {
      errors.push(
        looksLikeTemplate(id)
          ? `sidebar entry "${id}" points at an underscore/template scaffold — templates must not appear in navigation`
          : allDocs.has(id)
            ? `sidebar entry "${id}" is a draft doc — removed from the production build and its navigation`
            : `sidebar entry "${id}" does not resolve to any governed doc (dangling navigation id)`,
      );
    }
  }

  // --- 1b. Every internal sidebar link must resolve to a governed-doc route.
  // Hash-only (#anchor) links are internal but resolve to no governed doc.
  const sidebarLinkRoutes = new Set();
  for (const href of acc.links) {
    if (isExternalHref(href)) continue; // external links are out of scope
    if (!href.startsWith('/')) {
      errors.push(`sidebar link href "${href}" must be an absolute internal route (starting with "/") or an external URL — it does not resolve to a governed-doc route`);
      continue;
    }
    const route = stripBase(href);
    sidebarLinkRoutes.add(route);
    if (!validRoutes.has(route)) {
      errors.push(
        looksLikeTemplate(route)
          ? `sidebar link href "${href}" points at an underscore/template path — templates must not appear in navigation`
          : `sidebar link href "${href}" does not resolve to any governed-doc route (stale/dangling navigation link)`,
      );
    }
  }

  // --- 2. Locate the inventory page by its file (stable anchor), across the
  // whole universe (so a draft inventory page is caught, not silently missing).
  let inventory = null;
  for (const [docId, info] of allDocs) {
    if (info.rel === INVENTORY_REL) {
      inventory = { docId, ...info };
      break;
    }
  }

  if (inventory === null) {
    errors.push(`inventory page not found / not governed at docs/${INVENTORY_REL}`);
  } else {
    if (inventory.draft) {
      errors.push('inventory page is draft:true — the production build removes it from navigation');
    }
    if (inventory.unlisted) {
      errors.push('inventory page is unlisted:true — hidden from the sidebar and search');
    }
    if (inventory.slug !== INVENTORY_SLUG) {
      errors.push(
        `inventory page slug is ${inventory.slug === null ? '(none)' : `"${inventory.slug}"`} — must be exactly the clean slug "${INVENTORY_SLUG}"`,
      );
    }
    if (!sidebarDocSet.has(inventory.docId) && !sidebarLinkRoutes.has(inventory.route)) {
      errors.push(
        `inventory page ("${inventory.docId}") is missing from the docs-site sidebar (sidebars.js) — not present as a doc entry or a link to "${inventory.route}"; it would be a hidden, slug-only URL`,
      );
    }
  }

  // --- 3. Linked from the docs-site index (landing page) by EXACT target, in
  // the rendered Markdown body — inline OR an actually-USED reference link.
  if (!existsSync(INDEX_DOC)) {
    errors.push('docs-site index (docs/index.md) not found');
  } else {
    let body = '';
    try {
      ({ content: body } = matter(readFileSync(INDEX_DOC, 'utf8'), MATTER_OPTS));
    } catch {
      body = '';
    }
    const indexText = strippedMarkdown(body);

    const targets = [];
    // inline links: [text](target)
    for (const m of indexText.matchAll(/\]\(\s*(<[^>]+>|[^)\s]+)/g)) targets.push(m[1]);

    // reference links require BOTH a definition and an actual use — an unused
    // definition renders nothing, so it must not count.
    const defs = new Map(); // label -> target
    for (const m of indexText.matchAll(/^[ ]{0,3}\[([^\]]+)\]:\s*(<[^>]+>|\S+)/gm)) {
      defs.set(m[1].trim().toLowerCase(), m[2]);
    }
    const usedLabels = new Set();
    // full [text][label] and collapsed [text][]
    for (const m of indexText.matchAll(/\[([^\]]+)\]\[([^\]]*)\]/g)) {
      usedLabels.add((m[2].trim() || m[1].trim()).toLowerCase());
    }
    // shortcut [label] (not followed by [, ( or : — i.e. not a use of/def for another form)
    for (const m of indexText.matchAll(/\[([^\]]+)\](?!\s*[[(:])/g)) {
      usedLabels.add(m[1].trim().toLowerCase());
    }
    for (const label of usedLabels) if (defs.has(label)) targets.push(defs.get(label));

    const matchesInventory = (raw) => {
      const t = raw.replace(/^<|>$/g, '').trim();
      if (!t) return false;
      const noAnchor = t.split('#')[0].split('?')[0];
      if (!noAnchor) return false;
      if (stripBase(noAnchor) === INVENTORY_SLUG) return true;
      if (/\.mdx?$/.test(noAnchor) && !noAnchor.startsWith('/') && !isExternalHref(noAnchor)) {
        const resolved = posix.normalize(posix.join('.', noAnchor)).replace(/^\.\//, '');
        return resolved === INVENTORY_REL;
      }
      return false;
    };

    if (!targets.some(matchesInventory)) {
      errors.push(
        `docs-site index (docs/index.md) does not link to the inventory page by its exact rendered target (expected the .md link "${INVENTORY_REL}" or the slug "${INVENTORY_SLUG}", inline or as a used reference link)`,
      );
    }
  }

  // --- Report -------------------------------------------------------------
  if (errors.length > 0) {
    console.error('Docs-site navigation validation failed:\n');
    for (const e of errors) console.error(`  ✗ ${e}`);
    console.error(`\n${errors.length} error(s).`);
    process.exit(1);
  }

  console.log(
    `✓ Navigation OK — ${acc.docIds.length} sidebar doc entr(y/ies) + ${acc.links.length} link(s) resolve; ` +
      `inventory page "${inventory.docId}" is in the sidebar, linked from the index by exact target, and keeps its clean slug.`,
  );
  process.exit(0);
}

main();
